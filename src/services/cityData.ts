// Helper: Haversine distance in Kilometers between two lat/lng points
export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Manhattan street factor (usually 1.25x to 1.35x crow-flies in urban grids)
export function calculateUrbanTravelTimeMin(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number,
  speedKmh = 40,
  trafficFactor = 1.0,
  weatherFactor = 1.0
): number {
  const directDist = calculateDistanceKm(lat1, lon1, lat2, lon2);
  const networkDist = directDist * 1.28; // Urban road geometry factor
  const effectiveSpeed = (speedKmh / (trafficFactor * weatherFactor)) || 30;
  const travelHours = networkDist / effectiveSpeed;
  return travelHours * 60; // in minutes
}

// Find zone by point coordinates (approximate point in polygon / nearest centroid)
export function getZoneForCoordinates(lat: number, lng: number, zones = INITIAL_ZONES): Zone {
  let closestZone = zones[0];
  let minDistance = Infinity;

  for (const zone of zones) {
    const d = calculateDistanceKm(lat, lng, zone.centroide[0], zone.centroide[1]);
    if (d < minDistance) {
      minDistance = d;
      closestZone = zone;
    }
  }
  return closestZone;
}

